
"""
LLM-based explanation for Custom CNN chest X-ray predictions.

The LLM receives prediction metadata, not the X-ray itself.
It explains model outputs in accessible language and must not
claim that a prediction is a confirmed medical diagnosis.
"""

import os
import time
from pathlib import Path

from dotenv import load_dotenv
from google import genai
from google.genai import errors


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parents[2]

load_dotenv(BASE_DIR / ".env")

DEFAULT_MODEL = "gemini-3.8-flash"

MAX_RETRIES = 3
INITIAL_RETRY_DELAY = 2


# ============================================================
# GEMINI EXPLANATION
# ============================================================

def generate_explanation(
    predictions,
    selected_label,
    gradcam_layer,
):
    """
    Generate a human-readable explanation using Gemini.

    Args:
        predictions: Sorted list of prediction dictionaries.
        selected_label: Label selected for Grad-CAM.
        gradcam_layer: Name of the convolutional layer used.

    Returns:
        Text generated by Gemini.

    Raises:
        ValueError: Missing API key.
        RuntimeError: Gemini generation failed.
    """

    api_key = os.getenv("GEMINI_API_KEY")

    model_name = os.getenv(
        "GEMINI_MODEL",
        DEFAULT_MODEL,
    )

    if not api_key:
        raise ValueError(
            "GEMINI_API_KEY is missing. "
            "Add it to the project-root .env file."
        )

    # --------------------------------------------------------
    # PREDICTION METADATA
    # --------------------------------------------------------

    prediction_summary = [
        {
            "label": item["label"],
            "model_score_percent": round(
                item["probability"] * 100,
                2,
            ),
        }
        for item in predictions[:5]
    ]

    # --------------------------------------------------------
    # PROMPT
    # --------------------------------------------------------

    prompt = f"""
You are a medical education assistant for an academic
Explainable AI chest X-ray classification project.

Your FIRST responsibility is to clearly state the selected
CNN prediction. Do not begin with a general introduction.

CNN predictions:
{prediction_summary}

Selected CNN label: {selected_label}
Grad-CAM layer: {gradcam_layer}

Generate the response using EXACTLY these sections and this order:

## 1. Predicted Condition or Finding: {selected_label}

Start by naming the selected label exactly as provided:
"{selected_label}"

Explain that this is the highest-scoring label selected by
the CNN, not a confirmed medical diagnosis.

Report its model score from the supplied prediction data:
{prediction_summary}

Do not invent a different score.

## 2. What Is {selected_label}?

Explain the meaning of this condition or radiographic finding
in simple, understandable language.

Important:
- If the label is a radiographic finding, say so.
- Do not incorrectly present a finding as a confirmed disease.
- Do not invent patient-specific findings.

## 3. Common Symptoms

List common symptoms associated with the selected condition
when medically appropriate.

Symptoms are general medical information, not symptoms
detected by the CNN or extracted from the X-ray.

Never claim that this particular user has these symptoms.

## 4. Common Chest X-Ray Characteristics

Describe general radiographic characteristics associated
with the selected label.

Clearly distinguish general medical knowledge from findings
actually observed in the uploaded image.

You have NOT received the actual X-ray or Grad-CAM heatmap.
Do not claim to have visually examined either image.

## 5. Grad-CAM Explanation

Explain that Grad-CAM highlights image regions that influenced
the CNN's selected prediction.

State that a heatmap does not prove the disease is present.

Do not describe specific highlighted regions because the
heatmap image was not supplied to you.

## 6. Important Medical Note

Explain that the CNN's score is not necessarily a calibrated
clinical probability and that its output may be incorrect.

This is an academic research prototype, not a diagnostic tool.
Recommend qualified medical evaluation for health concerns.

STYLE RULES:
- Name the predicted label immediately in section 1.
- Use short paragraphs and clear bullet points.
- Keep the response understandable to a general user.
- Do not add a long introduction.
- Do not invent medical facts, citations, or patient information.
- Do not provide a treatment plan or definitive diagnosis.
"""

    # --------------------------------------------------------
    # GEMINI CLIENT
    # --------------------------------------------------------

    client = genai.Client(
        api_key=api_key,
    )

    # --------------------------------------------------------
    # GENERATION WITH RETRIES
    # --------------------------------------------------------

    for attempt in range(MAX_RETRIES):

        try:

            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
            )

            explanation = getattr(
                response,
                "text",
                None,
            )

            if not explanation:
                raise RuntimeError(
                    "Gemini returned an empty explanation."
                )

            return explanation.strip()

        except errors.ServerError as exc:

            # Retry temporary server errors only.

            if exc.code not in (500, 502, 503, 504):
                raise RuntimeError(
                    f"Gemini server error: {exc}"
                ) from exc

            if attempt == MAX_RETRIES - 1:
                raise RuntimeError(
                    "Gemini is temporarily unavailable. "
                    "Please try again later."
                ) from exc

            delay = INITIAL_RETRY_DELAY * (2 ** attempt)

            time.sleep(delay)

        except errors.ClientError as exc:

            raise RuntimeError(
                f"Gemini request rejected: {exc}"
            ) from exc

    raise RuntimeError(
        "Gemini explanation could not be generated."
    )
